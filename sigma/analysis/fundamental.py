"""Fundamental bias for an instrument, in [-1, 1] (+ favours the base / the asset)."""
from __future__ import annotations

import math

from ..data import macro
from ..symbols import Instrument

SAFE_HAVEN = {"JPY": 1.0, "CHF": 0.8, "USD": 0.4, "XAU": 0.8}
RISK_ON = {"AUD": 1.0, "NZD": 1.0, "CAD": 0.6, "ZAR": 1.0, "MXN": 1.0, "BTC": 0.8, "ETH": 0.8}


def _t(x, scale):
    return 0.0 if x is None else math.tanh(x / scale)


def _risk_beta(ccy: str) -> float:
    return SAFE_HAVEN.get(ccy, 0.0) - RISK_ON.get(ccy, 0.0)


def _cot_score(asset: str) -> tuple[float, dict | None]:
    c = macro.cot(asset)
    if not c:
        return 0.0, None
    s = (c["cot_index_52w"] - 50) / 50
    if c["cot_index_52w"] > 90 or c["cot_index_52w"] < 10:
        s *= 0.3  # crowded positioning: reversal risk, so trust it less
    s = 0.6 * s + 0.4 * _t(c["net_change_4w"], abs(c["net_speculative"]) * 0.25 + 1)
    return max(-1, min(1, s)), c


def analyze(inst: Instrument) -> dict:
    if not inst.has_fundamentals:
        why = ("Basket index: a weighted basket of currencies, scored on technicals only."
               if inst.asset_class == "basket" else
               "Synthetic index: generated by a random number generator, no fundamentals or news apply.")
        return {"score": 0.0, "available": False, "notes": [why]}
    parts: dict[str, float] = {}
    data: dict = {}
    notes: list[str] = []
    risk = macro.risk_backdrop()
    data["risk"] = risk
    vix_move = risk.get("vix_chg_20d")

    if inst.asset_class == "forex":
        b, q = inst.base, inst.quote
        sb, sq = macro.short_rate(b), macro.short_rate(q)
        lb, lq = macro.long_rate(b), macro.long_rate(q)
        if sb is not None and sq is not None:
            diff = macro.latest(sb) - macro.latest(sq)
            d_chg = (macro.change(sb, 90) or 0) - (macro.change(sq, 90) or 0)
            parts["rate_differential"] = 0.5 * _t(diff, 3) + 0.5 * _t(d_chg, 0.5)
            data["short_rate_diff"] = diff
            data["short_rate_diff_chg_90d"] = d_chg
            notes.append(f"{b}-{q} short-rate gap {diff:+.2f}pp ({d_chg:+.2f}pp over 3 months)")
        if lb is not None and lq is not None:
            y_chg = (macro.change(lb, 60) or 0) - (macro.change(lq, 60) or 0)
            parts["yield_spread_momentum"] = _t(y_chg, 0.3)
            data["long_yield_spread_chg_60d"] = y_chg
        cb, cq = (_cot_score(b) if b != "USD" else (0.0, None)), (_cot_score(q) if q != "USD" else (0.0, None))
        if cb[1] or cq[1]:
            parts["cot_positioning"] = (cb[0] - cq[0]) / (2 if cb[1] and cq[1] else 1)
            data["cot"] = {b: cb[1], q: cq[1]}
        if vix_move is not None:
            parts["risk_sentiment"] = _t(vix_move, 4) * (_risk_beta(b) - _risk_beta(q)) / 2

    elif inst.asset_class == "metal":
        if risk.get("real_yield_chg_30d") is not None:
            parts["real_yields"] = -_t(risk["real_yield_chg_30d"], 0.25)
            notes.append(f"US 10y real yield {risk['real_yield_10y']:.2f}% "
                         f"({risk['real_yield_chg_30d']:+.2f} over 30d) - rising real yields weigh on gold")
        if risk.get("usd_index_chg_30d_pct") is not None:
            parts["dollar"] = -_t(risk["usd_index_chg_30d_pct"], 1.5)
        s, c = _cot_score(inst.base)
        if c:
            parts["cot_positioning"] = s
            data["cot"] = c
        if vix_move is not None:
            parts["risk_sentiment"] = 0.5 * _t(vix_move, 4)

    elif inst.asset_class == "crypto":
        fg = macro.crypto_fear_greed()
        if fg:
            parts["fear_greed_contrarian"] = (50 - fg["value"]) / 100
            data["fear_greed"] = fg
            notes.append(f"Crypto Fear & Greed {fg['value']} ({fg['label']})")
        if risk.get("usd_index_chg_30d_pct") is not None:
            parts["dollar"] = -_t(risk["usd_index_chg_30d_pct"], 2)
        if vix_move is not None:
            parts["risk_sentiment"] = -_t(vix_move, 4)

    else:  # indices / stocks
        if vix_move is not None:
            parts["risk_sentiment"] = -_t(vix_move, 3)

    score = sum(parts.values()) / len(parts) if parts else 0.0
    if not parts:
        notes.append("No fundamental data available (add a FRED_API_KEY for macro data).")
    return {"score": max(-1.0, min(1.0, score)), "available": bool(parts), "parts": parts,
            "data": data, "notes": notes}
